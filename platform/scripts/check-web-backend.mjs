// Called only by test_web_browser.py with disposable local account credentials.
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const config = JSON.parse(readFileSync(0, 'utf8'));
const cli = process.env.AGENT_BROWSER_CLI;
if (!cli) throw new Error('Set AGENT_BROWSER_CLI.');
const run = (...args) => execFileSync(process.execPath, [cli, '--session', 'umuve-web-backend', '--allowed-domains', '127.0.0.1,localhost', ...args], { encoding: 'utf8', timeout: 30000 });
const evaluate = code => run('eval', code);
const wait = text => run('wait', '--fn', `document.body.innerText.includes(${JSON.stringify(text)})`);
const click = name => run('find', 'role', 'button', 'click', '--name', name, '--exact');
const base = 'http://127.0.0.1:3107';
const image = config.photoFile;
try {
  run('open', base + '/driver/login');
  evaluate(`localStorage.setItem('umuve-auth', ${JSON.stringify(JSON.stringify({ version: 0, state: { token: config.token, user: config.user } }))})`);
  run('open', base + `/driver/jobs/${config.jobId}/active`);
  wait('Before Photos');
  run('wait', '--fn', `Array.from(document.querySelectorAll('button')).some(button=>button.textContent.includes('Take / Select Photos') && !button.disabled)`);
  run('upload', 'input[type=file]', image);
  wait('Before photos saved');
  run('reload'); wait('Before Photos');
  run('wait', 'img[alt="Before Photos 1"]');
  run('wait', '--fn', 'document.querySelector(\'img[alt="Before Photos 1"]\').naturalWidth > 0');
  console.log('PASS Uploaded proof restores and loads from real API storage');
  click('Start Job'); wait('After Photos');
  run('upload', 'input[type=file]', image);
  wait('After photos saved');
  click('Complete Job'); wait('Complete this job?');
  run('wait', 'input[autocomplete="one-time-code"]');
  click('Yes, Complete Job');
  wait("The customer's handoff PIN is required");
  run('fill', 'input[autocomplete="one-time-code"]', config.pin === '0000' ? '1111' : '0000');
  click('Yes, Complete Job'); wait('That handoff PIN is not correct');
  console.log('PASS Real backend refuses missing and incorrect handoff PINs; dialog remains editable');
  run('set', 'viewport', '390', '844');
  evaluate('if(document.documentElement.scrollWidth > innerWidth) throw new Error("Mobile overflow")');
  run('screenshot', '/private/tmp/umuve-web-pin.png');
  run('fill', 'input[autocomplete="one-time-code"]', config.pin);
  click('Yes, Complete Job'); wait('Test connection interrupted after completion');
  run('reload'); wait('Retry saved update');
  click('Retry saved update'); wait('Saved update confirmed');
  wait('Job Complete!');
  evaluate(`if(!document.body.innerText.includes('144.00')) throw new Error('Driver pay missing')`);
  evaluate(`(async()=>{const r=indexedDB.open('umuve-browser-work',1);const db=await new Promise(resolve=>r.onsuccess=()=>resolve(r.result));const saved=await new Promise(resolve=>{const q=db.transaction('drafts').objectStore('drafts').get(${JSON.stringify(`proof:${config.user.id}:${config.jobId}`)});q.onsuccess=()=>resolve(q.result)});db.close();if(saved)throw new Error('Completed pickup work was not cleared')})()`);
  console.log('PASS Uploaded proof, required PIN and interrupted completion recover through real Flask routes');
  run('set', 'viewport', '1280', '900');
  run('open', base + '/driver/earnings'); wait('Earnings History');
  run('wait', '--fn', 'document.body.innerText.toLowerCase().includes("finish payout setup")');
  evaluate(`if(!document.body.innerText.includes('$144.00')) throw new Error('Actual earnings missing')`);
  run('screenshot', '/private/tmp/umuve-web-backend-earnings.png');
  console.log('PASS Real payment records appear in Pro earnings without a browser API stub');
  click('Notifications'); wait('Pickup reminder');
  run('snapshot', '-i');
  run('screenshot', '/private/tmp/umuve-web-notifications-desktop.png');
  evaluate(`if(document.body.innerText.includes('Private pickup')) throw new Error('Another account notification was exposed')`);
  click('Unread: Pickup reminder');
  run('wait', '--fn', '!document.querySelector(\'[aria-label="Unread: Pickup reminder"]\')');
  run('reload'); wait('Earnings History'); click('Notifications'); wait('Pickup reminder');
  evaluate(`if(document.querySelector('[aria-label="Unread: Pickup reminder"]')) throw new Error('Read state did not persist')`);
  run('wait', '[aria-label="Unread: Pickup update"]');
  run('set', 'viewport', '390', '844');
  evaluate(`for(const label of ['Close notifications', 'Unread: Pickup update']) {const r=document.querySelector('[aria-label="'+label+'"]').getBoundingClientRect();if(r.left<0 || r.right>innerWidth || r.top<0 || r.bottom>innerHeight) throw new Error('Notification control outside mobile viewport: '+label)}`);
  run('snapshot', '-i');
  run('screenshot', '/private/tmp/umuve-web-notifications-mobile.png');
  click('Read all');
  run('wait', '--fn', '!document.querySelector(\'[aria-label^="Unread: "]\')');
  run('reload'); wait('Earnings History'); click('Notifications'); wait('Pickup update');
  evaluate(`if(document.querySelector('[aria-label^="Unread: "]')) throw new Error('Read-all state did not persist')`);
  const errors = JSON.parse(run('--json', 'errors'));
  assert.equal(errors.success, true);
  assert.deepEqual(errors.data.errors, [], 'Browser runtime errors');
  console.log('PASS Pro notifications support individual and bulk read actions, persist after reload, and work at mobile width through the real API');
} catch (reason) {
  run('screenshot', '/private/tmp/umuve-web-backend-failure.png');
  console.error(run('snapshot'));
  console.error(run('--json', 'errors'));
  throw reason;
} finally {
  run('close');
}
