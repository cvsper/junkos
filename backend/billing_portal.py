def main():
    argv = sys.argv[1:]
    if not argv or argv[0] in ("-h", "--help"):
        print(__doc__)
        return
    if argv[0] == "bootstrap":
        cfg = bootstrap()
        print(json.dumps(cfg, indent=2))
        return
    if argv[0] == "subscribe" and len(argv) >= 2:
        org_id = argv[1]
        tier = argv[2] if len(argv) >= 3 else None
