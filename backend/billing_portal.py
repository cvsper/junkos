"""
B2B Commercial Portal — Stripe billing (Spec 04 §8).

BILLING OWNERSHIP (audit F24 — one owner per charge, never two)
================================================================
Two systems can bill an org, and they must never both charge the base fee for
the same period:

  * **Stripe Subscription** (``subscribe_org`` / ``create_checkout_session``,
    ``org.stripe_subscription_id`` set): Stripe charges the tier's monthly
    base automatically. It OWNS the base fee. Contract invoices generated by
    ``portal_invoicing`` for such an org carry usage/overage lines only.
  * **Contract invoice** (``portal_invoicing.generate_monthly_invoices``, org
    has an active ``Contract`` but NO Stripe subscription — e.g. enterprise
    net-30, invoiced): the monthly invoice OWNS the base fee and adds one
    ``kind='base_fee'`` line.

``base_fee_owner(org)`` is the single decision point and
``claim_base_fee(org_id, period, kind)`` is the idempotency lock: it inserts an
``AutomationEvent`` keyed ``(portal_base_fee, org_period, "<org_id>:<YYYY-MM>")``
so a second attempt (any path, any run) to bill the base fee for the same
period fails the unique constraint and is skipped.

Included pickups are always covered by whoever owns the base fee; overage
pickups are always billed on the contract invoice.

Responsibilities of this module:
  1. Bootstrap the catalog: create Product + Price rows for Starter/Pro/
     Enterprise tiers in Stripe (or report the existing IDs). Idempotent —
     we look up by name before creating. Price IDs land in
     `portal_billing_config.json` so the app can subscribe orgs without
     hitting the Stripe API every time.
  2. Subscribe an org: find-or-create the Stripe customer, attach a
     subscription at the chosen tier, and store the resulting IDs on Org.
  3. Deliver contract invoices to Stripe (``push_portal_invoice_to_stripe``):
     draft first, line items attached explicitly to that draft, every Stripe
     id persisted, idempotency keys derived from (org_id, period) so retries
     are safe.

Usage:
    STRIPE_API_KEY=sk_test_... python billing_portal.py bootstrap
    STRIPE_API_KEY=sk_test_... python billing_portal.py subscribe <org_id> <tier>

The webhook handler is registered under /portal/v1/billing/webhook — it only
cares about checkout.session.completed, invoice.paid, invoice.payment_failed,
and customer.subscription.updated (to sync tier + status). It fails closed in
production when STRIPE_WEBHOOK_SECRET_PORTAL is unset (see webhook_guard).
"""

