# ---------------------------------------------------------------------------
# Config persistence — small JSON file; product/price IDs are public-safe
# ---------------------------------------------------------------------------
def _load_config():
    if CONFIG_PATH.exists():
        try:
            return json.loads(CONFIG_PATH.read_text())
        except Exception:
            return {}
    return {}


def _save_config(cfg):
    try:
        CONFIG_PATH.write_text(json.dumps(cfg, indent=2))
    except Exception:
        # On read-only / ephemeral filesystems the cache write can fail; that's
        # fine — resolve_tier_price_id() rediscovers from Stripe when needed.
        logger.warning("could not persist portal billing config to %s", CONFIG_PATH)


def _stripe_key(override=None):
    """Stripe secret key. Prefer STRIPE_SECRET_KEY (used by the rest of the
    backend); fall back to the legacy STRIPE_API_KEY name."""
    return override or os.environ.get("STRIPE_SECRET_KEY") or os.environ.get("STRIPE_API_KEY", "")


def _stripe_client(override=None):
    """Return the configured ``stripe`` module (api_key set) or None when no
    key is configured / SDK missing. Tests patch this to inject a fake."""
    key = _stripe_key(override)
    if not key:
        return None
    try:
        import stripe
    except ImportError:
        return None
    stripe.api_key = key
    return stripe


def period_key(period_start):
    """'YYYY-MM' key for a billing period (idempotency + Stripe keys)."""
    return "{:04d}-{:02d}".format(period_start.year, period_start.month)


def base_fee_owner(org):
    """'subscription' when Stripe charges the tier base automatically,
    'contract_invoice' when the monthly contract invoice must carry it."""
    if org is not None and getattr(org, "stripe_subscription_id", None):
        return "subscription"
    return "contract_invoice"


def claim_base_fee(org_id, period_start, kind):
    """Idempotency lock for billing the base fee once per (org, period).

    Inserts an AutomationEvent (unique on kind/subject) inside a savepoint.
    Returns True if THIS caller now owns the base fee for the period, False
    if it was already billed (by any path). Does not commit — the caller's
    transaction decides.
    """
    from sqlalchemy.exc import IntegrityError
    from models import db, AutomationEvent
    subject = "{}:{}".format(org_id, period_key(period_start))
    try:
        with db.session.begin_nested():
            db.session.add(AutomationEvent(
                kind="portal_base_fee", subject_type="org_period",
                subject_id=subject, detail=kind,
            ))
        return True
    except IntegrityError:
        return False


def base_fee_already_billed(org_id, period_start):
    from models import db, AutomationEvent
    subject = "{}:{}".format(org_id, period_key(period_start))
    return db.session.query(AutomationEvent.id).filter_by(
        kind="portal_base_fee", subject_type="org_period", subject_id=subject,
    ).first() is not None


def resolve_tier_price_id(tier):
    """Return the Stripe monthly price id for a tier.

    Prefers the cached config file, but if it's missing (Render's filesystem is
    ephemeral across redeploys / multi-instance), rediscovers the price from
    Stripe by product name + amount — the same way bootstrap() does — so
    checkout/subscribe don't break with "run bootstrap first" after a redeploy.
    Only raises if the product/price genuinely isn't in Stripe yet.
    """
    if tier not in TIERS:
        raise ValueError("invalid tier {}".format(tier))
    pid = _load_config().get("tiers", {}).get(tier, {}).get("base_price_id")
    if pid:
        return pid

    import stripe
    key = _stripe_key()
    if not key:
        raise RuntimeError("Stripe key not set")
    stripe.api_key = key
    meta = TIERS[tier]
    product = next(
        (p for p in stripe.Product.list(limit=100).auto_paging_iter()
         if p.name == meta["name"]),
        None,
    )
    if not product:
        raise RuntimeError("tier {} not bootstrapped in Stripe — run bootstrap".format(tier))
    price = next(
        (pr for pr in stripe.Price.list(product=product.id, limit=10).auto_paging_iter()
         if pr.unit_amount == meta["monthly_cents"]
         and pr.recurring and pr.recurring.interval == "month"),
        None,
    )
    if not price:
        raise RuntimeError("no monthly price for tier {} in Stripe".format(tier))
    # Best-effort re-cache so subsequent calls skip the lookup.
    cfg = _load_config()
    cfg.setdefault("tiers", {}).setdefault(tier, {}).update(
        {"product_id": product.id, "base_price_id": price.id}
    )
    _save_config(cfg)
    return price.id


# ---------------------------------------------------------------------------
# Bootstrap: create products + prices in Stripe (idempotent)
# ---------------------------------------------------------------------------
def bootstrap(stripe_api_key=None):
    """Create or reuse Stripe products + prices for all tiers. Returns the
    full config dict. Requires stripe SDK; skips if not installed."""
    try:
        import stripe
    except ImportError:
        raise SystemExit(
            "stripe SDK not installed. Run: pip install stripe"
        )

    stripe.api_key = _stripe_key(stripe_api_key)
    if not stripe.api_key:
        raise SystemExit("Stripe key not set (STRIPE_SECRET_KEY)")

    cfg = _load_config()
    cfg.setdefault("tiers", {})

    for tier, meta in TIERS.items():
        existing = cfg["tiers"].get(tier, {})
        product_id = existing.get("product_id")
        base_price_id = existing.get("base_price_id")

        if not product_id:
            products = stripe.Product.list(limit=100)
            match = next(
                (p for p in products.auto_paging_iter() if p.name == meta["name"]),
                None,
            )
            if match:
                product_id = match.id
            else:
                p = stripe.Product.create(
                    name=meta["name"],
                    description=meta["description"],
                    metadata={"tier": tier, "source": "portal_bootstrap"},
                )
                product_id = p.id

        if not base_price_id:
            prices = stripe.Price.list(product=product_id, limit=10)
            match = next(
                (
                    pr
                    for pr in prices.auto_paging_iter()
                    if pr.unit_amount == meta["monthly_cents"]
                    and pr.recurring
                    and pr.recurring.interval == "month"
                ),
                None,
            )
            if match:
                base_price_id = match.id
            else:
                pr = stripe.Price.create(
                    product=product_id,
                    unit_amount=meta["monthly_cents"],
                    currency="usd",
                    recurring={"interval": "month"},
                    nickname="{} Monthly".format(tier),
                )
                base_price_id = pr.id

        cfg["tiers"][tier] = {
            "product_id": product_id,
            "base_price_id": base_price_id,
            "monthly_cents": meta["monthly_cents"],
            "overage_cents": meta["overage_cents"],
        }

    cfg["bootstrapped_at"] = datetime.utcnow().isoformat()
    _save_config(cfg)
    return cfg


